// Backwards-compatible default (English)
export const CATEGORY_SUGGESTIONS = Object.fromEntries(
  Object.entries(BILINGUAL_SUGGESTIONS).map(([k, v]) => [k, v.en])
);

/**
 * Returns suggestion for category and language ('en' | 'bn')
 */
export function getCategorySuggestion(cat, lang = 'en') {
  const item = BILINGUAL_SUGGESTIONS[cat];
  if (!item) return null;
  return item[lang] || item.en;
}

/**
 * Given a question/category, find which category it belongs to and convert to target language
 */
export function convertSuggestion(cat, targetLang = 'en') {
  const item = BILINGUAL_SUGGESTIONS[cat];
  if (!item) return null;
  return item[targetLang] || item.en;
}
